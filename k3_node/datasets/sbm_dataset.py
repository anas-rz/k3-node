import os.path as osp
from typing import Any, Callable, List, Optional, Union
import numpy as np
from keras import ops

from k3_node.data import Data, InMemoryDataset
from k3_node.utils.random import stochastic_blockmodel_graph


class StochasticBlockModelDataset(InMemoryDataset):
    r"""A synthetic graph dataset generated by the stochastic block model.

    Args:
        root (str): Root directory where the dataset should be saved.
        block_sizes ([int] or array): The sizes of blocks.
        edge_probs ([[float]] or array): The density of edges between blocks.
        num_graphs (int, optional): The number of graphs. (default: 1)
        num_channels (int, optional): The number of node features. (default: None)
        is_undirected (bool, optional): Whether the graph is undirected. (default: True)
        transform (callable, optional): Transform function.
        pre_transform (callable, optional): Pre-transform function.
        force_reload (bool, optional): Whether to re-process the dataset.
    """

    def __init__(
        self,
        root: str,
        block_sizes: Union[List[int], np.ndarray],
        edge_probs: Union[List[List[float]], np.ndarray],
        num_graphs: int = 1,
        num_channels: Optional[int] = None,
        is_undirected: bool = True,
        transform: Optional[Callable] = None,
        pre_transform: Optional[Callable] = None,
        force_reload: bool = False,
        **kwargs: Any,
    ):
        self.block_sizes = np.array(block_sizes, dtype=np.int64)
        self.edge_probs = np.array(edge_probs, dtype=np.float32)
        assert num_graphs > 0

        self.num_graphs = num_graphs
        self.num_channels = num_channels
        self.is_undirected = is_undirected

        self.kwargs = {
            "n_informative": num_channels,
            "n_redundant": 0,
            "flip_y": 0.0,
            "shuffle": False,
        }
        self.kwargs.update(kwargs)

        super().__init__(root, transform, pre_transform, force_reload=force_reload)
        self.load(self.processed_paths[0])

    @property
    def processed_dir(self) -> str:
        return osp.join(self.root, self.__class__.__name__, "processed")

    @property
    def processed_file_names(self) -> str:
        bs = self.block_sizes.flatten().tolist()
        hash1 = "-".join([f"{x:.1f}" for x in bs])
        ep = self.edge_probs.flatten().tolist()
        hash2 = "-".join([f"{x:.1f}" for x in ep])
        return f"data_{self.num_channels}_{hash1}_{hash2}_{self.num_graphs}.pt"

    def process(self):
        try:
            from sklearn.datasets import make_classification
        except ImportError:
            make_classification = None

        edge_index = stochastic_blockmodel_graph(
            self.block_sizes, self.edge_probs, directed=not self.is_undirected
        )

        num_samples = int(self.block_sizes.sum())
        num_classes = len(self.block_sizes)

        data_list = []
        for _ in range(self.num_graphs):
            x = None
            if self.num_channels is not None:
                if make_classification is not None:
                    x_raw, y_not_sorted = make_classification(
                        n_samples=num_samples,
                        n_features=self.num_channels,
                        n_classes=num_classes,
                        weights=self.block_sizes / num_samples,
                        **self.kwargs,
                    )
                    x_raw = x_raw[np.argsort(y_not_sorted)]
                    x = ops.convert_to_tensor(x_raw.astype(np.float32), dtype="float32")
                else:
                    x = ops.convert_to_tensor(
                        np.random.randn(num_samples, self.num_channels).astype(np.float32),
                        dtype="float32",
                    )

            y_np = np.repeat(np.arange(num_classes, dtype=np.int64), self.block_sizes)
            y = ops.convert_to_tensor(y_np, dtype="int64")

            data = Data(x=x, edge_index=edge_index, y=y)
            if self.pre_transform is not None:
                data = self.pre_transform(data)
            data_list.append(data)

        self.save(data_list, self.processed_paths[0])


class RandomPartitionGraphDataset(StochasticBlockModelDataset):
    r"""The random partition graph dataset from the "How to Find Your Friendly
    Neighborhood: Graph Attention Design with Self-Supervision" paper.
    """

    def __init__(
        self,
        root: str,
        num_classes: int,
        num_nodes_per_class: int,
        node_homophily_ratio: float,
        average_degree: float,
        num_graphs: int = 1,
        num_channels: Optional[int] = None,
        is_undirected: bool = True,
        transform: Optional[Callable] = None,
        pre_transform: Optional[Callable] = None,
        **kwargs: Any,
    ):
        self._num_classes = num_classes
        self.num_nodes_per_class = num_nodes_per_class
        self.node_homophily_ratio = node_homophily_ratio
        self.average_degree = average_degree

        ec_over_v2 = average_degree / num_nodes_per_class
        p_in = node_homophily_ratio * ec_over_v2
        p_out = (ec_over_v2 - p_in) / (num_classes - 1)

        block_sizes = [num_nodes_per_class for _ in range(num_classes)]
        edge_probs = [[p_out for _ in range(num_classes)] for _ in range(num_classes)]
        for r in range(num_classes):
            edge_probs[r][r] = p_in

        super().__init__(
            root,
            block_sizes,
            edge_probs,
            num_graphs=num_graphs,
            num_channels=num_channels,
            is_undirected=is_undirected,
            transform=transform,
            pre_transform=pre_transform,
            **kwargs,
        )

    @property
    def processed_file_names(self) -> str:
        return (
            f"data_{self.num_channels}_{self._num_classes}_"
            f"{self.num_nodes_per_class}_{self.node_homophily_ratio:.1f}_"
            f"{self.average_degree:.1f}_{self.num_graphs}.pt"
        )

